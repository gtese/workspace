INSERT INTO timesheets (user_id, period, rnd_hours, non_rnd_hours, total_hours, attendance_hours, status)
SELECT e.user_id, '2026-10',
       COALESCE(SUM(CASE WHEN p.is_rnd     THEN e.hours ELSE 0 END), 0),
       COALESCE(SUM(CASE WHEN NOT p.is_rnd THEN e.hours ELSE 0 END), 0),
       COALESCE(SUM(e.hours), 0),
       COALESCE((SELECT hours FROM attendance a
                  WHERE a.user_id = e.user_id AND a.period = '2026-10'), 0),
       'draft'
  FROM time_entries e
  JOIN projects p ON p.id = e.project_id
 WHERE to_char(e.work_date, 'YYYY-MM') = '2026-10'
 GROUP BY e.user_id
ON CONFLICT (user_id, period) DO UPDATE
   SET rnd_hours        = EXCLUDED.rnd_hours,
       non_rnd_hours    = EXCLUDED.non_rnd_hours,
       total_hours      = EXCLUDED.total_hours,
       attendance_hours = EXCLUDED.attendance_hours,
       status           = 'draft';

COMMIT;



